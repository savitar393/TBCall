-- GA-1: independently assigned aggregate reporting, never a clinical-access grant.
CREATE TABLE reporting_catalogues (
    version varchar(100) PRIMARY KEY,
    namespace varchar(30) NOT NULL CHECK (namespace='KEMENDAGRI'),
    effective_on date NOT NULL,
    checked_on date NOT NULL,
    source_manifest jsonb NOT NULL,
    entries_checksum varchar(64) NOT NULL
);
CREATE TABLE reporting_regions (
    catalogue_version varchar(100) NOT NULL REFERENCES reporting_catalogues(version),
    code varchar(20) NOT NULL,
    level varchar(20) NOT NULL CHECK (level IN ('PROVINCE','REGENCY')),
    name varchar(255) NOT NULL,
    parent_code varchar(20),
    parent_level varchar(20),
    PRIMARY KEY(catalogue_version,code),
    UNIQUE(catalogue_version,code,level),
    FOREIGN KEY(catalogue_version,parent_code,parent_level)
        REFERENCES reporting_regions(catalogue_version,code,level),
    CHECK ((level='PROVINCE' AND parent_code IS NULL AND parent_level IS NULL)
        OR (level='REGENCY' AND parent_code IS NOT NULL AND parent_level='PROVINCE'))
);
CREATE TABLE reporting_grants (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id),
    catalogue_version varchar(100) NOT NULL REFERENCES reporting_catalogues(version),
    scope varchar(20) NOT NULL CHECK (scope IN ('NATIONAL','PROVINCE','REGENCY')),
    region_code varchar(20),
    version bigint NOT NULL DEFAULT 0 CHECK (version>=0),
    assigned_by uuid NOT NULL REFERENCES users(id),
    assigned_at timestamptz NOT NULL,
    revoked_by uuid REFERENCES users(id),
    revoked_at timestamptz,
    FOREIGN KEY(catalogue_version,region_code,scope)
        REFERENCES reporting_regions(catalogue_version,code,level),
    CHECK ((scope='NATIONAL' AND region_code IS NULL) OR (scope<>'NATIONAL' AND region_code IS NOT NULL)),
    CHECK ((revoked_at IS NULL AND revoked_by IS NULL) OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL))
);
CREATE UNIQUE INDEX uq_reporting_active_grant
    ON reporting_grants(user_id,catalogue_version,scope,COALESCE(region_code,'')) WHERE revoked_at IS NULL;
CREATE INDEX idx_reporting_active_grants ON reporting_grants(user_id) WHERE revoked_at IS NULL;
CREATE TABLE reporting_publication_guard (id integer PRIMARY KEY CHECK(id=1), sequence bigint NOT NULL DEFAULT 0);
