CREATE TABLE reporting_snapshots (
    id uuid PRIMARY KEY,
    catalogue_version varchar(100) NOT NULL REFERENCES reporting_catalogues(version),
    version bigint NOT NULL DEFAULT 0 CHECK(version>=0),
    state varchar(20) NOT NULL CHECK(state IN ('DRAFT','PUBLISHED')),
    data_as_of timestamptz NOT NULL,
    -- Monotonic capture order under the shared guard; application clocks never decide freshness.
    capture_sequence bigint NOT NULL UNIQUE CHECK(capture_sequence>0),
    created_by uuid NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL,
    public_data jsonb NOT NULL,
    -- Private disclosure ledger, never serialized by an API or included in logs/audits.
    private_contributions jsonb NOT NULL,
    published_by uuid REFERENCES users(id),
    published_at timestamptz,
    published_sequence bigint UNIQUE,
    CHECK ((state='DRAFT' AND published_by IS NULL AND published_at IS NULL AND published_sequence IS NULL)
        OR (state='PUBLISHED' AND published_by IS NOT NULL AND published_at IS NOT NULL AND published_sequence IS NOT NULL))
);
CREATE FUNCTION guard_reporting_snapshot() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' OR OLD.state='PUBLISHED' OR NEW.state<>'PUBLISHED'
       OR NEW.version<>OLD.version+1
       OR NEW.catalogue_version IS DISTINCT FROM OLD.catalogue_version
       OR NEW.data_as_of IS DISTINCT FROM OLD.data_as_of
       OR NEW.capture_sequence IS DISTINCT FROM OLD.capture_sequence
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.public_data IS DISTINCT FROM OLD.public_data
       OR NEW.private_contributions IS DISTINCT FROM OLD.private_contributions THEN
        RAISE EXCEPTION 'reporting snapshot is immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_reporting_snapshot_immutable BEFORE UPDATE OR DELETE ON reporting_snapshots
    FOR EACH ROW EXECUTE FUNCTION guard_reporting_snapshot();
